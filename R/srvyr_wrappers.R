#' Cross-tabulation using srvyr
#'
#' @param data A survey design created with survey::svydesign
#' @param yvar A string denoting the name of the dependent variable
#' @param xvar A string denoting the name of the independent variable
#' @param controlvar A string denoting the name of the control variable
#' @param digits A number indicating the precision of percentages (default = 0)
#' @param ... Other arguments passed through the function (not currently implemented)
#'
#' @returns A tibble
#'
#' @importFrom dplyr select group_by summarise mutate
#' @importFrom srvyr as_survey_design survey_total
#' @importFrom stats na.omit
#'
#' @export
#'
#' @examples
#' library(survey)
#' data("ab")
#' absvy <- svydesign(~1, data = ab, weights = ~weight)
#' table_vote1 <- crossTab(absvy, yvar = "dvote3", xvar = "educ")
#' table_vote1
crossTab <- function(data, yvar, xvar, controlvar = NULL, digits = 0, ...) {

  if(is.null(controlvar)){

    out <- srvyr::as_survey_design(data) %>%
      dplyr::select(!!sym(xvar), !!sym(yvar)) %>%
      stats::na.omit() %>%
      dplyr::group_by(!!sym(xvar), !!sym(yvar)) %>%
      dplyr::summarise(count = srvyr::survey_total(),
                       pct = srvyr::survey_prop())
    #ggplot() +
    #aes(x = xvar, y = pct, fill = yvar,
    #    label = paste0(round(pct*100, digits = digits),"%")) +
    #geom_bar(stat = "identity") +
    #geom_text(position = position_stack(.5)) +
    #scale_fill_manual(values = c("#0C9EBD", "#E04541", "#c1c1c1"))

  }

  if(!is.null(controlvar)){

    out <- srvyr::as_survey_design(data) %>%
      dplyr::select(!!sym(controlvar), !!sym(xvar), !!sym(yvar)) %>%
      stats::na.omit() %>%
      dplyr::group_by(!!sym(controlvar), !!sym(xvar), !!sym(yvar)) %>%
      dplyr::summarise(count = srvyr::survey_total(),
                       pct = srvyr::survey_prop())
    #ggplot() +
    #aes(x = xvar, y = pct, fill = yvar,
    #    label = paste0(round(pct*100, digits = digits),"%")) +
    #facet_wrap(~controlvar)
    #geom_bar(stat = "identity") +
    #geom_text(position = position_stack(.5)) +
    #scale_fill_manual(values = c("#0C9EBD", "#E04541", "#c1c1c1"))

  }

  attr(out, "xvar") <- xvar
  attr(out, "yvar") <- yvar
  if(!is.null(controlvar)) { attr(out, "controlvar") <- controlvar }

  #attr(out, "class") <- c(attr(out, "class"), "crossTab")

  return(out)

}



